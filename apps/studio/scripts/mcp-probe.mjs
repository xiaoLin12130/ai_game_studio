#!/usr/bin/env node
/**
 * Drive the real chain: DSH runtime → DSH MCP client → Studio MCP server (official SDK).
 *
 * Two modes:
 *   (default)  handshake only — proves the server starts, is discovered and answers
 *              tools/list. Spends no model quota.
 *   --prompt   sends one prompt asking the model to call get_studio_health, then checks
 *              the server's audit log for the actual tools/call.
 *
 * Credentials: the commandcode key is read from the user's own ~/.dsh/.credentials.yaml
 * and handed to the runtime through its documented apiKeyEnv. It is never logged.
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
import { spawnSync } from 'node:child_process'

const require = createRequire(import.meta.url)
const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const REPO = path.resolve(ROOT, '..', '..')
const OUT = process.env.STUDIO_MCP_PROBE_OUT
  ? path.resolve(process.env.STUDIO_MCP_PROBE_OUT)
  : path.join(REPO, 'evidence', 'phase-01-b', 'mcp')
const RUN = fs.mkdtempSync(path.join(os.tmpdir(), 'studio-mcp-probe-'))

const WITH_PROMPT = process.argv.includes('--prompt')
const PROVIDER = process.env.STUDIO_PROVIDER ?? 'commandcode'
const MODEL = process.env.STUDIO_MODEL ?? 'deepseek/deepseek-v4-flash'

/** Read COMMANDCODE_API_KEY from the user's credential store without printing it. */
function readCommandCodeKey() {
  const file = path.join(os.homedir(), '.dsh', '.credentials.yaml')
  if (!fs.existsSync(file)) return null
  const text = fs.readFileSync(file, 'utf8')
  const match = /COMMANDCODE_API_KEY\s*:\s*"((?:[^"\\]|\\[\s\S])*)"/.exec(text)
  return match ? match[1].replace(/\\\r?\n\s*/g, '') : null
}

const { pathToFileURL } = await import('node:url')
const { HarnessClient } = await import(
  pathToFileURL(path.join(ROOT, 'node_modules', '@deepseek-ai', 'dsh-sdk-client', 'lib', 'index.js')).href
)

const auditLog = path.join(RUN, 'mcp-audit.jsonl')
const dshHome = path.join(RUN, 'dsh-home')
const profileDir = path.join(dshHome, 'profiles', 'sdk')

/**
 * The isolated home needs two things before a patched run can work:
 *   1. a real `sdk` profile materialised from DSH's own template, which ships the base
 *      services the provider and the MCP client wait on (`llm` and `tools`);
 *   2. the third-party provider installed into that profile, which is how DSH's own
 *      plugin manager does it.
 * Writing a package.json by hand does not work: it creates a profile shell with no
 * services, and every patched entry then waits forever.
 */
async function provisionProfile(clientCtor) {
  const providerManifest = path.join(profileDir, 'node_modules', '@mars-sea', 'dsh-commandcode-provider', 'package.json')
  if (fs.existsSync(providerManifest)) return { provisioned: false, reason: 'already present' }

  const bootstrap = new clientCtor({ dshHome, profile: 'sdk', initializeTimeoutMs: 60000, env })
  let bootstrapped = false
  try {
    bootstrap.start()
    await bootstrap.initialize({ cwd: RUN, provider: 'deepseek-official', model: 'deepseek-v4-flash' })
    bootstrapped = true
  } catch {
    bootstrapped = false
  } finally {
    try { await Promise.race([bootstrap.close(), new Promise((r) => setTimeout(r, 15000))]) } catch {}
  }

  // Use DSH's own plugin manager: it resolves against the runtime's compatibility rules,
  // which plain npm does not (`npm install` happily pulls a dsh-session that this runtime
  // then refuses to load).
  const dshBin = path.join(ROOT, 'node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js')
  const install = spawnSync(
    process.execPath,
    [dshBin, 'plugin', '--profile', 'sdk', 'add', '@mars-sea/dsh-commandcode-provider@0.15.4'],
    { cwd: ROOT, encoding: 'utf8', timeout: 300000, env: { ...process.env, DSH_HOME: dshHome } },
  )
  return {
    bootstrapped,
    provisioned: install.status === 0,
    exitCode: install.status,
    reason: install.status === 0 ? 'installed into the generated profile' : String(install.stderr ?? '').slice(-300),
  }
}

const patch = path.join(RUN, 'mcp.cordis.yml')
fs.writeFileSync(
  patch,
  [
    '# Generated by scripts/mcp-probe.mjs — commandcode provider + the Studio MCP server.',
    '- insert:',
    '    - id: llm-commandcode',
    "      name: '@mars-sea/dsh-commandcode-provider'",
    '      config:',
    '        apiKeyEnv: COMMANDCODE_API_KEY',
    '    - id: studio-mcp',
    "      name: '@deepseek-ai/dsh-mcp-client'",
    '      config:',
    '        serverName: studio',
    '        transport: stdio',
    '        command: ' + JSON.stringify(process.execPath),
    '        args:',
    '          - ' + JSON.stringify(path.join(ROOT, 'mcp', 'studio-mcp-server.mjs')),
    '        env:',
    '          ELECTRON_RUN_AS_NODE: "1"',
    '          STUDIO_MCP_AUDIT_LOG: ' + JSON.stringify(auditLog),
    '        failOnStartupError: true',
    '        toolCallTimeoutMs: 60000',
    '',
  ].join('\n'),
)

const key = readCommandCodeKey()
const env = { ...process.env }
if (key) env.COMMANDCODE_API_KEY = key

const report = {
  generatedAt: new Date().toISOString(),
  mode: WITH_PROMPT ? 'prompt' : 'handshake-only',
  provider: PROVIDER,
  model: MODEL,
  credentialPresent: Boolean(key),
  serverScript: path.relative(REPO, path.join(ROOT, 'mcp', 'studio-mcp-server.mjs')),
  sdkVersion: (() => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules', '@modelcontextprotocol', 'sdk', 'package.json'), 'utf8')).version } catch { return null } })(),
  events: [],
  profileProvisioning: null,
}

const profileProvisioning = await provisionProfile(HarnessClient)
report.profileProvisioning = profileProvisioning
const client = new HarnessClient({ dshHome, profile: 'sdk', patches: [patch], initializeTimeoutMs: 60000, env })
const notifications = []
let subError = null
const sub = client.subscribe()
const drain = (async () => {
  try {
    for await (const n of sub) {
      notifications.push(n)
      if (n.method === 'session.event') {
        const event = n.params?.event
        if (event?.type === 'assistant/message' || event?.type === 'tool/call' || event?.type === 'tool/result' || event?.type === 'request/header') {
          report.events.push({ type: event.type, summary: JSON.stringify(event.data ?? {}).slice(0, 400) })
        }
      }
    }
  } catch (error) {
    subError = error
  }
})()

let exitCode = null
try {
  client.start()
  const init = await client.initialize({ cwd: RUN, provider: PROVIDER, model: MODEL })
  report.serverInfo = init?.serverInfo ?? null
  report.toolDiscovery = { expected: 'mcp__studio__get_studio_health' }

  if (WITH_PROMPT) {
    const sessionId = 'studio-mcp-' + Date.now()
    await client.prompt(sessionId, [
      {
        type: 'text',
        text:
          '你必须先调用工具 mcp__studio__get_studio_health 获取真实数据，然后只输出一行：' +
          'TOOL_STATUS=<返回 JSON 里的 status 字段值> SERVER_PHASE=<返回 JSON 里 studio.phase 的值>。' +
          '不要编造，必须来自工具结果。',
      },
    ])
    const started = Date.now()
    while (Date.now() - started < 240000) {
      const idle = notifications.some((n) => n.method === 'session.status' && n.params?.status === 'idle')
      if (idle) break
      await new Promise((r) => setTimeout(r, 250))
    }
    await new Promise((r) => setTimeout(r, 500))
  }
} catch (error) {
  report.error = String(error?.message ?? error).slice(0, 600)
} finally {
  try {
    await Promise.race([client.close(), new Promise((r) => setTimeout(r, 20000))])
  } catch (error) {
    report.closeError = String(error?.message ?? error).slice(0, 300)
  }
  await Promise.race([drain, new Promise((r) => setTimeout(r, 5000))])
  exitCode = /exit code: (-?\d+)/.exec(String(subError?.message ?? ''))?.[1] ?? null
  try { sub.close() } catch {}
}

report.runtimeExitCode = exitCode === null ? null : Number(exitCode)
report.audit = fs.existsSync(auditLog)
  ? fs.readFileSync(auditLog, 'utf8').split(/\r?\n/).filter(Boolean).map((line) => { try { return JSON.parse(line) } catch { return { raw: line.slice(0, 200) } } })
  : []
report.auditKinds = report.audit.map((entry) => entry.kind)
report.initialized = report.auditKinds.includes('initialize.completed')
report.toolCalled = report.auditKinds.includes('tools/call')
report.toolServed = report.auditKinds.includes('tools/call.served')
report.ok = Boolean(report.serverInfo) && report.initialized && (!WITH_PROMPT || (report.toolCalled && report.toolServed))

fs.mkdirSync(OUT, { recursive: true })
const file = path.join(OUT, WITH_PROMPT ? 'tool-call.json' : 'handshake.json')
fs.writeFileSync(file, JSON.stringify(report, null, 2) + '\n')
try { fs.rmSync(RUN, { recursive: true, force: true }) } catch {}

console.log(JSON.stringify({ ok: report.ok, mode: report.mode, initialized: report.initialized, toolCalled: report.toolCalled, exitCode: report.runtimeExitCode, events: report.events.length }, null, 2))
process.exit(report.ok ? 0 : 1)
