#!/usr/bin/env node
/**
 * Does this DSH build actually have web tools, and can they reach the network?
 *
 * The audit found web-search-deepseek configured with apiKeyEnv: DEEPSEEK_API_KEY, and this
 * machine has no such key. Rather than assume, this asks the runtime what tools it exposes
 * and then, if a fetch tool is there, asks the model to use it once.
 *
 * Costs one small model turn. Writes a JSON report; never prints the credential.
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const REPO = path.resolve(ROOT, '..', '..')
const OUT = path.join(REPO, 'evidence', 'phase-02', 'capability')
const require = createRequire(import.meta.url)

const PROVIDER = 'commandcode'
const MODEL = 'deepseek/deepseek-v4-flash'

function readKey() {
  const file = path.join(os.homedir(), '.dsh', '.credentials.yaml')
  if (!fs.existsSync(file)) return null
  const text = fs.readFileSync(file, 'utf8')
  const m = /COMMANDCODE_API_KEY\s*:\s*"((?:[^"\\]|\\[\s\S])*)"/.exec(text)
  return m ? m[1].replace(/\\\r?\n\s*/g, '') : null
}

const key = readKey()
if (key) process.env.COMMANDCODE_API_KEY = key

const run = fs.mkdtempSync(path.join(os.tmpdir(), 'studio-webprobe-'))
const dshHome = path.join(run, 'dsh-home')
fs.mkdirSync(dshHome, { recursive: true })

const patch = path.join(run, 'web.cordis.yml')
fs.writeFileSync(
  patch,
  [
    '# Generated by scripts/web-capability-probe.mjs — provider row only.',
    '- insert:',
    '    - id: llm-commandcode',
    "      name: '@mars-sea/dsh-commandcode-provider'",
    '      config:',
    '        apiKeyEnv: COMMANDCODE_API_KEY',
    '',
  ].join('\n'),
)

const sdk = require('@deepseek-ai/dsh-sdk-client')

// The isolated home needs a real sdk profile with the provider installed; a hand-written
// package.json produces a shell with no services and every patched row waits forever.
const { spawnSync } = require('node:child_process')
const profileDir = path.join(dshHome, 'profiles', 'sdk')
const providerManifest = path.join(profileDir, 'node_modules', '@mars-sea', 'dsh-commandcode-provider', 'package.json')
let provisioning = { provisioned: false, reason: 'already present' }
if (!fs.existsSync(providerManifest)) {
  const bootstrap = new sdk.HarnessClient({ dshHome, profile: 'sdk', initializeTimeoutMs: 60000, env: process.env })
  try {
    bootstrap.start()
    await bootstrap.initialize({ cwd: run, provider: 'deepseek-official', model: 'deepseek-v4-flash' })
  } catch { /* the profile is materialised even when the handshake fails */ }
  finally { try { await Promise.race([bootstrap.close(), new Promise((r) => setTimeout(r, 15000))]) } catch {} }

  const dshBin = path.join(ROOT, 'node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js')
  const install = spawnSync(
    process.execPath,
    [dshBin, 'plugin', '--profile', 'sdk', 'add', '@mars-sea/dsh-commandcode-provider@0.15.4'],
    { cwd: ROOT, encoding: 'utf8', timeout: 300000, env: { ...process.env, DSH_HOME: dshHome } },
  )
  provisioning = { provisioned: install.status === 0, reason: String(install.stderr ?? '').slice(-300) }
}

const client = new sdk.HarnessClient({
  dshHome,
  profile: 'sdk',
  patches: [patch],
  initializeTimeoutMs: 60000,
  disposeGraceMs: 4000,
})

const report = {
  generatedAt: new Date().toISOString(),
  purpose: '验证当前 DSH 构建是否暴露联网工具，以及无 DEEPSEEK_API_KEY 时能否抓取网页',
  credentialPresent: Boolean(key),
  provisioning,
  deepseekApiKeyPresent: Boolean(process.env.DEEPSEEK_API_KEY),
  tools: [],
  fetchAttempt: null,
  searchAttempt: null,
  error: null,
}

try {
  client.start()
  await client.initialize({ cwd: ROOT, provider: PROVIDER, model: MODEL })

  const sessionId = 'web-probe-' + Date.now()
  const sub = client.subscribeSessionTree(sessionId)
  const events = []
  const drain = (async () => {
    try {
      for await (const n of sub) {
        if (n?.method === 'session.event' && n.params?.event) events.push(n.params.event)
      }
    } catch { /* runtime closed */ }
  })()

  await client.prompt(sessionId, [
    {
      type: 'text',
      text: 'Use your web search tool to search for "vampire survivors game design core loop". Report the titles and URLs of the first two results you get. If the search tool fails, reply with the exact error text.',
    },
  ])

  const deadline = Date.now() + 120000
  while (Date.now() < deadline) {
    const end = events.find((e) => e.type === 'turn/end')
    if (end) break
    await new Promise((r) => setTimeout(r, 200))
  }

  const payload = (e) => e?.data ?? e
  const texts = []
  for (const e of events) {
    if (e.type === 'assistant/message') {
      for (const block of payload(e).message?.content ?? []) {
        if (block.type === 'text') texts.push(block.text)
      }
    }
  }
  report.answer = texts.join('\n').slice(0, 1200)

  // The request header is the authoritative list of what the model was offered: it is what
  // the runtime actually sent, not what a plugin claims to provide.
  const header = events.find((e) => e.type === 'request/header')
  const offered = payload(header)?.header?.tools ?? []
  report.toolsOffered = offered.map((x) => x.name)
  report.webToolsOffered = report.toolsOffered.filter((n) => /web|fetch|search|browse/i.test(n))
  report.toolCount = report.toolsOffered.length

  report.tools = [...new Set(events.filter((e) => e.type === 'tool/call').map((e) => payload(e).name))]
  report.eventTypes = [...new Set(events.map((e) => e.type))]
  report.rawEventCount = events.length
  report.rawEventSample = events.slice(0, 40).map((e) => ({
    type: e.type,
    keys: Object.keys(e).slice(0, 8),
    text: e.type === 'assistant/message'
      ? (payload(e).message?.content ?? []).map((b) => b.type + ':' + String(b.text ?? b.name ?? '').slice(0, 160)).join(' | ')
      : e.type === 'tool/call' ? String(payload(e).name) + ' ' + String(payload(e).arguments ?? '').slice(0, 120)
      : e.type === 'tool/result' ? JSON.stringify(payload(e).message?.content ?? []).slice(0, 200)
      : undefined,
  }))

  sub.close()
  await drain.catch(() => {})
} catch (error) {
  report.error = String(error?.message ?? error).slice(0, 600)
} finally {
  try { await client.close() } catch { /* already gone */ }
}

fs.mkdirSync(OUT, { recursive: true })
fs.writeFileSync(path.join(OUT, 'web-capability.json'), JSON.stringify(report, null, 2) + '\n')
console.log(JSON.stringify({ tools: report.tools, error: report.error, answer: (report.answer ?? '').slice(0, 300) }, null, 2))
