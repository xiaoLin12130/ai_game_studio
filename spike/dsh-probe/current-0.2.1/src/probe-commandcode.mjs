/**
 * Probe CC-1 — real model reply through the user's actual provider.
 *
 * Constraint from PHASE 00-R1: the user runs the `commandcode` provider
 * (`@mars-sea/dsh-commandcode-provider`) on DSH 0.2.1-rc.3. Testing
 * `deepseek-official` instead would prove nothing about their setup, so this probe
 * mounts the same plugin into an isolated SDK profile and drives it through the
 * official TypeScript SDK.
 *
 * The prompt carries a random token. Only a real model can echo it back, so a
 * swallowed error or a stub cannot fake a pass.
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { DeepSeekHarness } from '@deepseek-ai/dsh-sdk-client'
import { createEvidence, p, step } from './lib/evidence.mjs'
import { dshHomePath, workspacePath } from './lib/paths.mjs'
import { findRuntimeProcesses, waitForRuntimeGone, clearStaleProfileLock, PROC } from './lib/proc.mjs'
import { EXIT, detectModelBlocker } from './lib/outcome.mjs'

const PROVIDER = process.env.CC_PROVIDER ?? 'commandcode'
const MODEL = process.env.CC_MODEL ?? 'deepseek/deepseek-v4.1-flash'
const PROFILE = process.env.CC_PROFILE ?? 'cc-sdk'
const TOKEN = `studio-${crypto.randomBytes(4).toString('hex')}`

const ev = createEvidence('cc-1-reply')
const summary = {
  probe: 'CC-1-reply',
  startedAt: new Date().toISOString(),
  provider: PROVIDER,
  model: MODEL,
  profile: PROFILE,
  token: TOKEN,
}

const dshHome = dshHomePath()
const workspace = workspacePath()
fs.mkdirSync(workspace, { recursive: true })
summary.lockRecovery = clearStaleProfileLock(dshHome)

// Mount the user's real provider bundle through an ordered patch. The plugin
// registers the `commandcode` route; the credential is referenced by env name only.
const patchPath = p('tmp', 'cc-provider.cordis.yml')
fs.mkdirSync(path.dirname(patchPath), { recursive: true })
const patchYaml = [
  '# Generated by probe-commandcode.mjs — mounts the user-supplied commandcode provider.',
  '# apiKeyEnv is a NAME, never a value: the runtime resolves it from its credential seam.',
  '- insert:',
  '    - id: llm-commandcode',
  "      name: '@mars-sea/dsh-commandcode-provider'",
  '      config:',
  '        apiKeyEnv: COMMANDCODE_API_KEY',
  '',
].join('\n')
fs.writeFileSync(patchPath, patchYaml)
summary.patchPath = patchPath

const harness = new DeepSeekHarness({
  profile: PROFILE,
  dshHome,
  cwd: workspace,
  provider: PROVIDER,
  model: MODEL,
  maxTokens: 512,
  requestTimeoutMs: 300000,
  initializeTimeoutMs: 300000,
  patches: [patchPath],
})

const notifications = []

try {
  const t0 = Date.now()
  await harness.start()
  summary.startMs = Date.now() - t0
  ev.append('runtime.started', { startMs: summary.startMs, profile: PROFILE })
  step('runtime started with commandcode patch', { startMs: summary.startMs })

  const running = findRuntimeProcesses({ dshHome })
  summary.processStatusWhileRunning = running.status
  summary.processCountWhileRunning = running.matches.length
  ev.append('runtime.processes', { status: running.status, matches: running.matches })

  const session = harness.session()
  summary.sessionId = session.id

  const prompt = [
    '请严格按照以下要求回答：',
    `生成一个随机标识并在回复中原样返回：验证标识：${TOKEN}`,
    '',
    '除此之外，用一句话说明你当前使用的是什么模型。',
  ].join('\n')
  summary.prompt = prompt

  const t1 = Date.now()
  const result = await session.run(prompt, {
    onNotification: (notification) => notifications.push({ method: notification.method, params: notification.params }),
  })
  summary.runMs = Date.now() - t1
  summary.finalResponse = result.finalResponse
  summary.eventCount = result.events.length
  summary.notificationMethods = [...new Set(result.notifications.map((n) => n.method))]
  summary.modelBlocker = detectModelBlocker(result.events)

  // Which provider actually served the request? `request/header` is written before
  // the provider call, so it is valid evidence even when the call then fails.
  const header = result.events.find((e) => e?.type === 'request/header')
  summary.requestRoute = header?.data?.header?.config ?? null
  const context = result.events.find((e) => e?.type === 'request/context')
  summary.requestContext = context?.data ?? null

  ev.append('run.completed', {
    runMs: summary.runMs,
    finalResponse: summary.finalResponse,
    eventCount: summary.eventCount,
    requestRoute: summary.requestRoute,
    modelBlocker: summary.modelBlocker,
  })
  step('model answered', JSON.stringify(String(summary.finalResponse).slice(0, 200)))

  const text = String(summary.finalResponse ?? '')
  summary.assertions = {
    echoToken: text.includes(TOKEN),
    nonEmptyResponse: text.trim().length > 0,
    routeIsCommandcode: summary.requestRoute?.provider === PROVIDER,
    modelAsRequested: summary.requestRoute?.model === MODEL,
    noProviderFallback: !summary.modelBlocker?.blocked,
  }
} catch (error) {
  summary.error = { name: error?.constructor?.name, message: String(error?.message ?? error).slice(0, 1500) }
  ev.append('probe.error', summary.error)
  step('ERROR', summary.error.message.slice(0, 300))
} finally {
  const t2 = Date.now()
  try {
    await harness.close()
    summary.closeMs = Date.now() - t2
  } catch (error) {
    summary.closeError = String(error?.message ?? error)
  }
  const reaped = await waitForRuntimeGone({ dshHome, boundMs: 25000 })
  summary.reap = { status: reaped.status, waitedMs: reaped.waitedMs, remaining: reaped.lastMatches, error: reaped.error }
  summary.assertions = { ...(summary.assertions ?? {}), processTreeGone: reaped.status === PROC.ABSENT }
  ev.append('runtime.reap', summary.reap)

  const allPass = summary.assertions && Object.values(summary.assertions).every(Boolean)
  const infraOk = !summary.error && reaped.status === PROC.ABSENT
  summary.verdict = allPass ? 'PASS' : infraOk && summary.modelBlocker?.blocked ? 'BLOCKED' : 'FAIL'

  summary.finishedAt = new Date().toISOString()
  ev.append('verdict', { verdict: summary.verdict, assertions: summary.assertions })
  ev.writeJson('summary.json', summary)
  step(`CC1_RESULT=${summary.verdict}`, summary.assertions)
  process.exitCode = EXIT[summary.verdict]
}

process.exit(typeof process.exitCode === 'number' ? process.exitCode : 0)
