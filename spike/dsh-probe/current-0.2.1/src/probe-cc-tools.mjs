/**
 * Probe CC-2 — the Studio read-only tool actually invoked by the real model.
 *
 * PHASE 00 could only prove registration: the provider refused, so no `tools/call`
 * ever reached Studio. This probe closes that gap on the user's real provider and
 * separates the three stages the review asked for:
 *
 *   1. Studio MCP server started and handshook
 *   2. the tool entered the model's tool roster
 *   3. the model called it AND the Studio server executed it (audit record)
 *
 * Only stage 3 counts as a完成的 tool-call chain.
 */
import fs from 'node:fs'
import path from 'node:path'
import { DeepSeekHarness } from '@deepseek-ai/dsh-sdk-client'
import { createEvidence, p, step } from './lib/evidence.mjs'
import { findRuntimeProcesses, waitForRuntimeGone, clearStaleProfileLock, PROC } from './lib/proc.mjs'
import { EXIT, STUDIO_TOOL_NAME, advertisedTools, detectModelBlocker } from './lib/outcome.mjs'

const PROVIDER = process.env.CC_PROVIDER ?? 'commandcode'
const MODEL = process.env.CC_MODEL ?? 'deepseek/deepseek-v4.1-flash'
const PROFILE = process.env.CC_PROFILE ?? 'cc-sdk'
const SERVER_SCRIPT = path.resolve(process.cwd(), '..', 'mcp', 'studio-mcp-server.mjs')

const ev = createEvidence('cc-2-tools')
const summary = {
  probe: 'CC-2-tools',
  startedAt: new Date().toISOString(),
  provider: PROVIDER,
  model: MODEL,
  profile: PROFILE,
  serverScript: SERVER_SCRIPT,
}

const dshHome = p('dsh-home')
const workspace = p('workspace')
fs.mkdirSync(workspace, { recursive: true })
summary.lockRecovery = clearStaleProfileLock(dshHome)

const patchDir = p('tmp')
fs.mkdirSync(patchDir, { recursive: true })
const auditLog = path.join(patchDir, 'studio-mcp-audit-cc.jsonl')
fs.writeFileSync(auditLog, '')

const toPosix = (value) => value.replace(/\\/g, '/')
const patchPath = path.join(patchDir, 'cc-tools.cordis.yml')
const patchYaml = [
  '# Generated by probe-cc-tools.mjs',
  '# Row 1: the user-supplied commandcode provider (credential by env NAME only).',
  '# Row 2: the official MCP bridge spawning the Studio read-only tool server.',
  '- insert:',
  '    - id: llm-commandcode',
  "      name: '@mars-sea/dsh-commandcode-provider'",
  '      config:',
  '        apiKeyEnv: COMMANDCODE_API_KEY',
  '    - id: studio-mcp',
  "      name: '@deepseek-ai/dsh-mcp-client'",
  '      config:',
  '        serverName: studio',
  '        transport: stdio',
  `        command: '${toPosix(process.execPath)}'`,
  '        args:',
  `          - '${toPosix(SERVER_SCRIPT)}'`,
  '        env:',
  `          STUDIO_MCP_AUDIT_LOG: '${toPosix(auditLog)}'`,
  '        failOnStartupError: true',
  '        toolCallTimeoutMs: 60000',
  '',
].join('\n')
fs.writeFileSync(patchPath, patchYaml)
summary.patchPath = patchPath
summary.patchYaml = patchYaml

const harness = new DeepSeekHarness({
  profile: PROFILE,
  dshHome,
  cwd: workspace,
  provider: PROVIDER,
  model: MODEL,
  maxTokens: 1024,
  requestTimeoutMs: 300000,
  initializeTimeoutMs: 300000,
  patches: [patchPath],
})

try {
  await harness.start()
  summary.started = true
  step('runtime started with commandcode + studio MCP')

  const session = harness.session()
  summary.sessionId = session.id

  const prompt = [
    '你必须先调用工具 mcp__studio__get_studio_health 获取真实数据，然后回答问题。',
    '回答格式严格如下两行，不要额外解释：',
    'status=<工具返回的 status 字段值>',
    'phase=<工具返回的 studio.phase 字段值>',
    '如果你没有成功调用工具，回答 TOOL_UNAVAILABLE。',
  ].join('\n')
  summary.prompt = prompt

  const result = await session.run(prompt)
  summary.finalResponse = result.finalResponse
  summary.eventCount = result.events.length
  summary.modelBlocker = detectModelBlocker(result.events)

  const header = result.events.find((e) => e?.type === 'request/header')
  summary.requestRoute = header?.data?.header?.config ?? null
  const tools = advertisedTools(result.events)
  summary.advertisedToolCount = tools?.length ?? null
  summary.studioToolAdvertised = Array.isArray(tools) && tools.includes(STUDIO_TOOL_NAME)
  step('model answered', JSON.stringify(String(summary.finalResponse).slice(0, 200)))

  const auditRaw = fs.readFileSync(auditLog, 'utf8').trim()
  const records = auditRaw ? auditRaw.split('\n').map((line) => JSON.parse(line)) : []
  const calls = records.filter((r) => r.kind === 'tools/call')
  const served = records.filter((r) => r.kind === 'tools/call.served')
  summary.audit = {
    totalRecords: records.length,
    kinds: [...new Set(records.map((r) => r.kind))],
    toolCalls: calls.map((c) => c.name),
    servedCount: served.length,
    initializedWith: records.find((r) => r.kind === 'initialize') ?? null,
  }
  ev.writeJson('audit-records.json', records)

  const text = String(summary.finalResponse ?? '')
  summary.assertions = {
    stage1_serverStarted: records.some((r) => r.kind === 'server.started'),
    stage1_handshaken: Boolean(summary.audit.initializedWith),
    stage2_toolAdvertised: summary.studioToolAdvertised === true,
    stage3_modelCalledTool: calls.some((c) => c.name === 'get_studio_health'),
    stage3_serverExecuted: served.length > 0,
    stage3_responseUsesToolData: /\bok\b/i.test(text) && /PHASE_00/i.test(text),
    routeIsCommandcode: summary.requestRoute?.provider === PROVIDER,
  }
  ev.append('assertions', summary.assertions)
  step('tool chain', summary.assertions)
} catch (error) {
  summary.error = { name: error?.constructor?.name, message: String(error?.message ?? error).slice(0, 1500) }
  ev.append('probe.error', summary.error)
  step('ERROR', summary.error.message.slice(0, 300))
} finally {
  try {
    await harness.close()
  } catch (error) {
    summary.closeError = String(error?.message ?? error)
  }
  const reaped = await waitForRuntimeGone({ dshHome, boundMs: 25000 })
  summary.reap = { status: reaped.status, waitedMs: reaped.waitedMs, remaining: reaped.lastMatches, error: reaped.error }

  const allPass = summary.assertions && Object.values(summary.assertions).every(Boolean) && reaped.status === PROC.ABSENT
  summary.verdict = allPass ? 'PASS' : summary.modelBlocker?.blocked ? 'BLOCKED' : 'FAIL'

  summary.finishedAt = new Date().toISOString()
  ev.writeJson('summary.json', summary)
  step(`CC2_RESULT=${summary.verdict}`, {
    called: summary.assertions?.stage3_modelCalledTool,
    executed: summary.assertions?.stage3_serverExecuted,
    reaped: reaped.status,
  })
  process.exitCode = EXIT[summary.verdict]
}

process.exit(typeof process.exitCode === 'number' ? process.exitCode : 0)
