/**
 * Probe E — the controlled tool bridge.
 *
 * PHASE 00 must show that DSH can read one read-only Studio business fact through a
 * sanctioned path. The SDK wire protocol has no tool-registration method, so the
 * supported route is the official MCP bridge: mount `@deepseek-ai/dsh-mcp-client`
 * through an ordered profile patch and let it spawn the Studio MCP server.
 *
 * Success requires BOTH sides to agree:
 *   - the tool server's own audit log shows a `tools/call` for get_studio_health,
 *   - the model's final text contains the values that only that tool can supply.
 * A model that merely "sounds right" cannot fake the audit line, and a bridge that
 * never reaches the model cannot produce the values.
 */
import fs from 'node:fs'
import { DeepSeekHarness } from '@deepseek-ai/dsh-sdk-client'
import { createEvidence, p, step } from './lib/evidence.mjs'
import { waitForRuntimeGone, clearStaleProfileLock, PROC } from './lib/proc.mjs'
import { EXIT, STUDIO_TOOL_NAME, advertisedTools, detectModelBlocker } from './lib/outcome.mjs'

const MODEL = process.env.PROBE_MODEL ?? 'deepseek-v4-flash'
const PROVIDER = process.env.PROBE_PROVIDER ?? 'deepseek-official'
const SERVER_SCRIPT = p('mcp', 'studio-mcp-server.mjs')

const ev = createEvidence('e-tools')
const summary = { probe: 'E-tools', startedAt: new Date().toISOString(), serverScript: SERVER_SCRIPT }

const dshHome = p('tmp', 'dsh-home')
const workspace = p('tmp', 'workspace')
const patchDir = p('tmp', 'patches')
const auditLog = p('tmp', 'audit', 'studio-mcp-audit.jsonl')
fs.mkdirSync(dshHome, { recursive: true })
fs.mkdirSync(workspace, { recursive: true })
fs.mkdirSync(patchDir, { recursive: true })
fs.mkdirSync(p(`tmp`, 'audit'), { recursive: true })
fs.writeFileSync(auditLog, '')
summary.lockRecovery = clearStaleProfileLock(dshHome)

/** Forward slashes keep the YAML free of escape ambiguity on Windows. */
const toPosix = (value) => value.replace(/\\/g, '/')

const patchPath = p('tmp', 'patches', 'studio-mcp.cordis.yml')
// Shape note: a launcher patch must wrap new rows in `insert:`. A bare row with a
// new `id` is treated as an override of an existing entry and fails with
// `patch: entry "<id>" not found`. The mcp-client README's bare-row example is a
// config-tree entry, not a --patch file.
const patchYaml = [
  '# Generated by probe-tools.mjs — mounts the Studio read-only MCP tool server.',
  '# The official MCP bridge is the only sanctioned tool path in DSH 0.1.5.',
  '# `insert:` is required: a bare new id is read as an override of a missing entry.',
  '- insert:',
  '    - id: studio-mcp',
  "      name: '@deepseek-ai/dsh-mcp-client'",
  '      config:',
  '        serverName: studio',
  '        transport: stdio',
  `        command: '${toPosix(process.execPath)}'`,
  '        args:',
  `          - '${toPosix(SERVER_SCRIPT)}'`,
  '        env:',
  `          STUDIO_MCP_AUDIT_LOG: '${toPosix(auditLog)}'`,
  '        failOnStartupError: true',
  '        toolCallTimeoutMs: 30000',
  '',
].join('\n')
fs.writeFileSync(patchPath, patchYaml)
summary.patchPath = patchPath
summary.patchYaml = patchYaml
ev.append('patch.written', { patchPath, patchYaml })
step('profile patch written', patchPath)

const harness = new DeepSeekHarness({
  profile: 'sdk',
  dshHome,
  cwd: workspace,
  provider: PROVIDER,
  model: MODEL,
  maxTokens: 1024,
  requestTimeoutMs: 180000,
  initializeTimeoutMs: Number(process.env.PROBE_INIT_TIMEOUT_MS ?? 180000),
  patches: [patchPath],
})

try {
  await harness.start()
  summary.started = true
  ev.append('runtime.started', {})
  step('runtime started with MCP patch')

  const session = harness.session()
  summary.sessionId = session.id
  const prompt =
    'Use the tool named mcp__studio__get_studio_health. Then answer on two lines exactly:\n' +
    'status=<the status field value>\n' +
    'phase=<the studio.phase field value>\n' +
    'Do not explain. If the tool is unavailable, answer TOOL_UNAVAILABLE.'
  summary.prompt = prompt

  const result = await session.run(prompt)
  summary.finalResponse = result.finalResponse
  summary.eventCount = result.events.length
  ev.append('run.completed', {
    finalResponse: result.finalResponse,
    eventCount: result.events.length,
    sessionId: result.sessionId,
  })
  step('model answered', JSON.stringify(result.finalResponse?.slice(0, 240)))

  // Did the model's tool call actually arrive at the Studio server?
  const auditRaw = fs.readFileSync(auditLog, 'utf8').trim()
  const auditRecords = auditRaw ? auditRaw.split('\n').map((line) => JSON.parse(line)) : []
  const calls = auditRecords.filter((r) => r.kind === 'tools/call')
  const served = auditRecords.filter((r) => r.kind === 'tools/call.served')
  summary.audit = {
    totalRecords: auditRecords.length,
    kinds: [...new Set(auditRecords.map((r) => r.kind))],
    toolCalls: calls.map((c) => c.name),
    servedCount: served.length,
    initializedWith: auditRecords.find((r) => r.kind === 'initialize') ?? null,
  }
  ev.append('audit.summary', summary.audit)
  ev.writeJson('audit-records.json', auditRecords)
  step('studio audit', summary.audit)

  const text = String(summary.finalResponse ?? '')
  const toolsInHeader = advertisedTools(result.events)
  summary.advertisedToolCount = toolsInHeader?.length ?? null
  summary.studioToolAdvertised = Array.isArray(toolsInHeader) && toolsInHeader.includes(STUDIO_TOOL_NAME)
  summary.modelBlocker = detectModelBlocker(result.events)

  summary.assertions = {
    studioServerHandshaken: summary.audit.initializedWith !== null,
    studioServerListedTools: summary.audit.kinds.includes('tools/list'),
    studioToolAdvertisedToModel: summary.studioToolAdvertised,
    dshCalledStudioTool: calls.some((c) => c.name === 'get_studio_health'),
    servedByStudio: served.length > 0,
    modelReportedStatus: /\bok\b/i.test(text),
    modelReportedPhase: /PHASE_00/i.test(text),
  }
  ev.append('assertions', summary.assertions)

  const registrationVerified =
    summary.assertions.studioServerHandshaken &&
    summary.assertions.studioServerListedTools &&
    summary.assertions.studioToolAdvertisedToModel
  const invocationVerified = summary.assertions.dshCalledStudioTool && summary.assertions.servedByStudio

  summary.verdict = invocationVerified
    ? 'PASS'
    : registrationVerified && summary.modelBlocker?.blocked
      ? 'BLOCKED'
      : registrationVerified
        ? 'BLOCKED'
        : 'FAIL'
  step(`PROBE_E_RESULT=${summary.verdict}`, {
    registrationVerified,
    invocationVerified,
    blocker: summary.modelBlocker?.kind ?? null,
  })
  process.exitCode = EXIT[summary.verdict]
} catch (error) {
  summary.error = { name: error?.constructor?.name, message: String(error?.message ?? error) }
  ev.append('probe.error', summary.error)
  step('ERROR', summary.error.message)
  process.exitCode = 1
} finally {
  try {
    await harness.close()
    ev.append('runtime.closed', {})
  } catch (error) {
    summary.closeError = String(error?.message ?? error)
  }
  const reaped = await waitForRuntimeGone({ dshHome, boundMs: 20000 })
  summary.childGoneAfterClose = reaped.status === PROC.ABSENT
  ev.append('runtime.reap', { status: reaped.status, waitedMs: reaped.waitedMs, remaining: reaped.lastMatches })
  summary.finishedAt = new Date().toISOString()
  ev.writeJson('summary.json', summary)
}

// The SDK keeps a child process and subscriptions alive; without an explicit exit a
// hung child would block the whole probe run and look like a silent pass.
process.exit(typeof process.exitCode === "number" ? process.exitCode : 0)
